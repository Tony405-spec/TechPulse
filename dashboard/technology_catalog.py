CATEGORY_DISPLAY_NAMES = {
    "Languages": "Languages & runtimes",
    "Frameworks": "Frameworks & libraries",
    "Tools": "Developer tools & platforms",
}
# Product spellings are normalized for display; these aliases do not enter model features.
NAME_DISPLAY_CORRECTIONS = {
    "ASP.NET CORE": "ASP.NET Core",
    "Clickhouse": "ClickHouse",
    "Cockroachdb": "CockroachDB",
    "Neo4J": "Neo4j",
    "Opencv": "OpenCV",
    "mlflow": "MLflow",
    "Scikit-Learn": "scikit-learn",
}

def with_display_names(frame: pd.DataFrame) -> pd.DataFrame:
    """Replace only UI labels using the stable within-category database ordinal."""
    if frame.empty:
        return frame.copy()
    if "category_ordinal" not in frame.columns:
        raise ValueError("Technology display mapping requires category_ordinal from PostgreSQL.")
    result = frame.copy()
    for category, catalog in DISPLAY_CATALOG.items():
        selected = result[result["category"].eq(category)]
        positions = selected["category_ordinal"].astype(int) - 1
        if not positions.empty and (positions.min() < 0 or positions.max() >= len(catalog)):
            raise ValueError(f"Display catalog for {category} does not cover PostgreSQL category ordinals.")
        names = [catalog[position] for position in positions]
        result.loc[selected.index, "technology_name"] = [NAME_DISPLAY_CORRECTIONS.get(name, name) for name in names]
        result.loc[selected.index, "category"] = CATEGORY_DISPLAY_NAMES.get(category, category)
    if result["technology_name"].astype(str).str.startswith("Synthetic ").any():
        raise ValueError("A synthetic placeholder name was not replaced by the display catalog.")
    if result["technology_name"].astype(str).str.casefold().duplicated().any():
        raise ValueError("Display technology names must be unique for unambiguous selection.")
    return result.drop(columns="category_ordinal").sort_values("technology_name", kind="stable").reset_index(drop=True)
